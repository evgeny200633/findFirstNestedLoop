#pragma once

/*! Максимальное число строк во вводимой программе.
*/
#define MAX_STR_COUNT 20

/*! Максимальная длина строки.
*/
#define MAX_STR_LENGTH 128

/*! Значение, показывающее, что вложенный цикл не найден.
*/
#define NO_NESTED_LOOPS -1

/*! Находит во введенной программе первый встретившийся вложенный цикл.
*
* Дан текст программы на языке Си (многострочный текст).
*
* Текст программы синтаксически верен и имеет следующее форматирование:
* каждый элементарный оператор языка записывается в отдельной строке,
* а составные операторы заключаются в фигурные скобки,
* фигурные скобки располагаются на отдельных строках.
*
* В программе не используются глобальные переменные,
* структурированные типы данных, типы данных «ссылка» и «указатель»,
* символьные и строковые константы, но могут встречаться однострочные комментарии (“//”).
*
* \param[in] text - исходный текст программы.
* \param[in] strCount - количество строк в исходном тексте.
* \param[in] startLine - строка, с которой начинать выполнять поиск.
* \return Индекс строки, в которой находится первый встретившийся вложенный цикл, или значение NO_NESTED_LOOPS, если таковой отсутствует.
*/
int findFirstNestedLoop(const char text[MAX_STR_COUNT][MAX_STR_LENGTH], int strCount, int startLine);

